function metrics_table = run_monte_carlo(vectors, nominal_plant, config, ...
        uncertainty_config, base_seed)
%RUN_MONTE_CARLO Run paired robustness trials for all controllers.

[controller_names, run_count] = validate_inputs( ...
    vectors, config, base_seed);
row_count = numel(controller_names) * run_count;
metric_rows = cell(row_count, 1);
row_index = 0;

for run_index = 0:(run_count - 1)
    [scenario, perturbed_plant, metadata] = ...
        generate_monte_carlo_scenario( ...
        run_index, base_seed, uncertainty_config, nominal_plant);
    for controller_index = 1:numel(controller_names)
        controller_name = controller_names(controller_index);
        simulation = simulate_control_system(controller_name, ...
            vectors.(char(controller_name)), perturbed_plant, config, ...
            scenario, metadata.measurement_noise_seed);
        metrics = calculate_control_metrics( ...
            simulation, scenario, perturbed_plant);
        row_index = row_index + 1;
        metric_rows{row_index} = append_metadata(metrics, metadata);
    end
end

metrics_table = struct2table(vertcat(metric_rows{:}), "AsArray", true);
end

function record = append_metadata(metrics, metadata)
record = metrics;
metadata_fields = fieldnames(metadata);
for index = 1:numel(metadata_fields)
    field_name = metadata_fields{index};
    record.(field_name) = metadata.(field_name);
end
end

function [controller_names, run_count] = validate_inputs( ...
        vectors, config, base_seed)
if ~isstruct(vectors) || ~isscalar(vectors) || ...
        ~isstruct(config) || ~isscalar(config) || ...
        ~all(isfield(config, ["controller_names", "monte_carlo_runs"])) || ...
        ~isstring(config.controller_names) || ...
        isempty(config.controller_names) || ...
        ~isnumeric(config.monte_carlo_runs) || ...
        ~isreal(config.monte_carlo_runs) || ...
        ~isscalar(config.monte_carlo_runs) || ...
        ~isfinite(config.monte_carlo_runs) || ...
        config.monte_carlo_runs < 1 || ...
        config.monte_carlo_runs ~= floor(config.monte_carlo_runs) || ...
        ~isnumeric(base_seed) || ~isreal(base_seed) || ...
        ~isscalar(base_seed) || ~isfinite(base_seed) || base_seed < 0 || ...
        base_seed ~= floor(base_seed)
    invalid_input();
end
controller_names = config.controller_names(:);
run_count = double(config.monte_carlo_runs);
if numel(unique(controller_names)) ~= numel(controller_names) || ...
        ~all(isfield(vectors, cellstr(controller_names))) || ...
        double(base_seed) + run_count - 1 > 2^32 - 1
    invalid_input();
end
end

function invalid_input()
error("twsbr:batch:invalid_input", ...
    "Monte Carlo inputs must define frozen controllers, runs, and seeds.");
end
