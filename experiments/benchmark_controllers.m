function complexity = benchmark_controllers(vectors, plant_params, config)
%BENCHMARK_CONTROLLERS Measure the common controller lifecycle cost.

[controller_names, repeats] = validate_inputs( ...
    vectors, plant_params, config);
controller_count = numel(controller_names);
calls = repmat(repeats, controller_count, 1);
total_seconds = zeros(controller_count, 1);
mean_step_runtime_us = zeros(controller_count, 1);
parameter_dimension = zeros(controller_count, 1);
measured_state = zeros(4, 1);

for controller_index = 1:controller_count
    controller_name = controller_names(controller_index);
    vector = vectors.(char(controller_name));
    controller = create_controller( ...
        controller_name, vector, plant_params, config);
    space = controller_parameter_space(controller_name);
    parameter_dimension(controller_index) = space.dimension;

    runtime_start = tic;
    for call_index = 1:repeats
        controller = reset_controller(controller);
        [control, controller] = controller_step( ...
            controller, 0.0, measured_state, 0.0);
        applied_u = min(max(control.u_raw, -plant_params.u_max), ...
            plant_params.u_max);
        controller = controller_after_actuation( ...
            controller, control.u_raw, applied_u);
    end
    total_seconds(controller_index) = toc(runtime_start);
    mean_step_runtime_us(controller_index) = ...
        total_seconds(controller_index) / repeats * 1e6;
end

complexity = table(controller_names, calls, total_seconds, ...
    mean_step_runtime_us, parameter_dimension, 'VariableNames', { ...
    'controller', 'calls', 'total_seconds', ...
    'mean_step_runtime_us', 'parameter_dimension'});
end

function [controller_names, repeats] = validate_inputs( ...
        vectors, plant_params, config)
if ~isstruct(vectors) || ~isscalar(vectors) || ...
        ~isstruct(config) || ~isscalar(config) || ...
        ~all(isfield(config, ["controller_names", "benchmark_repeats"])) || ...
        ~isstring(config.controller_names) || ...
        isempty(config.controller_names) || ...
        ~isnumeric(config.benchmark_repeats) || ...
        ~isreal(config.benchmark_repeats) || ...
        ~isscalar(config.benchmark_repeats) || ...
        ~isfinite(config.benchmark_repeats) || ...
        config.benchmark_repeats < 1 || ...
        config.benchmark_repeats ~= floor(config.benchmark_repeats) || ...
        ~isstruct(plant_params) || ~isscalar(plant_params) || ...
        ~isfield(plant_params, "u_max")
    invalid_input();
end
controller_names = config.controller_names(:);
repeats = double(config.benchmark_repeats);
if numel(unique(controller_names)) ~= numel(controller_names) || ...
        ~all(isfield(vectors, cellstr(controller_names)))
    invalid_input();
end
end

function invalid_input()
error("twsbr:batch:invalid_input", ...
    "Benchmark inputs must define frozen controllers and repeat count.");
end
